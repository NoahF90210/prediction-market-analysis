from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Any

from jsonschema import Draft202012Validator, FormatChecker

from src.portfolio.analysis import build_dashboard_payload
from src.portfolio.contracts import OUTPUT_FIELDS, normalize_input
from src.rebuild.protocol import canonical_json_bytes

ROOT = Path(__file__).resolve().parents[2]
PORTFOLIO_SCHEMA = ROOT / "schemas" / "portfolio-market.schema.json"
DEFAULT_FIXTURE = ROOT / "data" / "fixtures" / "portfolio_normalized.json"
DEFAULT_OUTPUT = ROOT / "data" / "derived" / "portfolio"
DEFAULT_DASHBOARD = ROOT / "static_dashboard" / "data.js"


class PortfolioValidationError(RuntimeError):
    """Raised when the compact portfolio contract cannot be validated."""


def validate_portfolio_row(row: dict[str, Any]) -> list[str]:
    schema = json.loads(PORTFOLIO_SCHEMA.read_text())
    validator = Draft202012Validator(schema, format_checker=FormatChecker())
    return [
        f"{'.'.join(str(part) for part in error.absolute_path) or '<root>'}: {error.message}"
        for error in sorted(validator.iter_errors(row), key=lambda item: list(item.absolute_path))
    ]


def _csv_value(value: Any) -> Any:
    if isinstance(value, (dict, list)):
        return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return value


def _write_rows(rows: list[dict[str, Any]], output_dir: Path) -> dict[str, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    json_path = output_dir / "portfolio_rows.json"
    json_path.write_bytes(canonical_json_bytes(rows) + b"\n")

    csv_path = output_dir / "portfolio_rows.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=OUTPUT_FIELDS, lineterminator="\n")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: _csv_value(row.get(field)) for field in OUTPUT_FIELDS})
    return {"rows_json": json_path, "rows_csv": csv_path}


def write_dashboard_payload(payload: dict[str, Any], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    content = (
        "// Generated by src.portfolio.cli from a bounded normalized input.\n"
        "window.DASHBOARD_DATA = "
        + json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False)
        + ";\n"
    )
    path.write_text(content)
    return path


def build_portfolio(
    input_path: Path,
    *,
    corpus_kind: str,
    output_dir: Path = DEFAULT_OUTPUT,
    dashboard_output: Path | None = DEFAULT_DASHBOARD,
) -> tuple[list[dict[str, Any]], dict[str, Any], dict[str, Path]]:
    rows, metadata = normalize_input(input_path)
    errors: list[str] = []
    for index, row in enumerate(rows):
        errors.extend(f"row[{index}].{error}" for error in validate_portfolio_row(row))
    if errors:
        raise PortfolioValidationError("Portfolio row validation failed:\n- " + "\n- ".join(errors))

    payload = build_dashboard_payload(rows, corpus_kind=corpus_kind, metadata=metadata)
    paths = _write_rows(rows, output_dir)
    summary_path = output_dir / "portfolio_summary.json"
    summary_path.write_bytes(canonical_json_bytes(payload) + b"\n")
    paths["summary"] = summary_path
    if dashboard_output is not None:
        paths["dashboard"] = write_dashboard_payload(payload, dashboard_output)
    return rows, payload, paths


def build_fixture_portfolio(
    *,
    output_dir: Path = DEFAULT_OUTPUT,
    dashboard_output: Path | None = DEFAULT_DASHBOARD,
) -> tuple[list[dict[str, Any]], dict[str, Any], dict[str, Path]]:
    return build_portfolio(
        DEFAULT_FIXTURE,
        corpus_kind="fixture",
        output_dir=output_dir,
        dashboard_output=dashboard_output,
    )
