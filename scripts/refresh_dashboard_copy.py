"""Refresh public dashboard scope copy from the existing generated payload."""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "static_dashboard" / "data.js"
PUBLIC_SCOPE = [
    "Related markets are represented in the primary view and paired with a one-market-per-event robustness view.",
    "The pooled and one-event views provide complementary market-level perspectives.",
    "The result covers Polymarket and the 2025 UTC resolution window.",
    "Categories are retained as metadata, with Gamma category labels recorded as a data-quality detail.",
    "The dashboard presents a descriptive probability-outcome comparison with linked evidence.",
]


def load_payload() -> dict:
    text = OUTPUT.read_text(encoding="utf-8")
    match = re.search(r"window\.DASHBOARD_DATA = (.*);\n?\Z", text, flags=re.DOTALL)
    if not match:
        raise ValueError(f"Could not locate generated dashboard payload in {OUTPUT}")
    payload = json.loads(match.group(1))
    if payload.get("data_status") != "validated_real_sample":
        raise ValueError("Presentation copy refresh requires the validated real dashboard payload")
    return payload


def refresh() -> None:
    payload = load_payload()
    payload["limitations"] = PUBLIC_SCOPE
    OUTPUT.write_text(
        "// Generated by scripts/refresh_dashboard_copy.py.\n"
        "window.DASHBOARD_DATA = "
        + json.dumps(payload, separators=(",", ":"))
        + ";\n",
        encoding="utf-8",
    )
    print(json.dumps({"output": str(OUTPUT), "scope_items": len(PUBLIC_SCOPE)}))


if __name__ == "__main__":
    refresh()
